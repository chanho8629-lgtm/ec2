-- 태그 추천/검색 테스트용 마스터 태그
-- 기존 25개 분야 x 40개 키워드 + AI/영상 전용 태그 추가
insert into tbl_tag (tag_name)
select category.name || '_' || keyword.name as tag_name
from (
    values
        ('영상'), ('브이로그'), ('쇼츠'), ('영화'), ('드라마'),
        ('음악'), ('게임'), ('스포츠'), ('여행'), ('음식'),
        ('패션'), ('뷰티'), ('테크'), ('교육'), ('비즈니스'),
        ('예술'), ('디자인'), ('사진'), ('라이프'), ('힐링'),
        ('리뷰'), ('뉴스'), ('반려동물'), ('자동차'), ('아웃도어'),
        ('AI'), ('생성AI'), ('숏폼'), ('유튜브'), ('릴스')
) as category(name)
cross join (
    values
        ('입문'), ('추천'), ('트렌드'), ('하이라이트'), ('리뷰'),
        ('튜토리얼'), ('챌린지'), ('감성'), ('일상'), ('꿀팁'),
        ('모음'), ('비하인드'), ('라이브'), ('클립'), ('명장면'),
        ('분석'), ('인터뷰'), ('아카이브'), ('프리뷰'), ('베스트'),
        ('초보자'), ('전문가'), ('아이디어'), ('실험'), ('창작'),
        ('영감'), ('기획'), ('제작'), ('편집'), ('촬영'),
        ('색감'), ('구도'), ('스토리'), ('캐릭터'), ('세계관'),
        ('컬렉션'), ('시리즈'), ('프로젝트'), ('포트폴리오'), ('큐레이션')
) as keyword(name)
on conflict (tag_name) do nothing;

